#!/usr/bin/env bash
# Cross-check the Rust <-> Lean map in scripts/trace.tsv against the RightCash
# submodule in rust/.
#  * every Rust symbol must occur in its file at the pinned commit (the commit
#    this repository records for rust/);
#  * every Lean name must exist in the built library; its source line is looked up;
#  * mapped Rust files that differ between the pin and REF are listed (proof drift).
# Usage: scripts/check_trace.sh [REF]
#   REF defaults to origin/main of the submodule; run `git -C rust fetch` first
#   to compare against the latest upstream.
# Writes TRACEABILITY.md. Exit status 1 if a symbol or name is missing.
set -u
here="$(cd "$(dirname "$0")/.." && pwd)"
rust="$here/rust"
ref="${1:-origin/main}"
commit="$(git -C "$here" ls-files -s rust | awk '{print $2}')"
if [[ -z "$commit" ]]; then
  echo "rust/ is not a registered submodule" >&2; exit 1
fi
if ! git -C "$rust" cat-file -e "$commit^{commit}" 2>/dev/null; then
  echo "pinned commit $commit is not available; run: git submodule update --init" >&2; exit 1
fi
if [[ "$(git -C "$rust" rev-parse HEAD)" != "$commit" ]]; then
  echo "warning: rust/ is not checked out at the pinned commit; links in TRACEABILITY.md may point at other lines" >&2
fi
out="$here/TRACEABILITY.md"
tmp="$(mktemp -d)"
fail=0

# Look up every Lean name's module and declaration line.
{
  echo "import Lean"; echo "import RightCash"
  echo "open Lean in"
  echo "#eval show CoreM Unit from do"
  echo "  let env ← getEnv"
  printf '  for s in ['
  grep -v '^#' "$here/scripts/trace.tsv" | awk -F'\t' 'NF >= 3 { printf "%s\"%s\"", sep, $3; sep = ", " }'
  echo "] do"
  echo "    let n := s.toName"
  echo "    let some idx := env.getModuleIdxFor? n | IO.println s!\"{s}\\tMISSING\\t0\""
  echo "    let mod := env.header.moduleNames[idx.toNat]!"
  echo "    let r ← match ← findDeclarationRanges? n with"
  echo "      | some r => pure (some r)"
  echo "      | none => findDeclarationRanges? n.getPrefix"
  echo "    IO.println s!\"{s}\\t{mod}\\t{r.map (·.range.pos.line) |>.getD 1}\""
} > "$tmp/Trace.lean"
if ! (cd "$here" && lake env lean "$tmp/Trace.lean" > "$tmp/lean.tsv" 2> "$tmp/lean.err"); then
  echo "Lean lookup failed:" >&2; cat "$tmp/lean.tsv" "$tmp/lean.err" >&2; exit 1
fi

{
  echo "# Rust ↔ Lean traceability"
  echo
  echo "Generated by \`scripts/check_trace.sh\` from \`scripts/trace.tsv\`. Rust locations"
  echo "refer to commit \`$commit\` of the \`rust/\` submodule."
  echo
  echo "| Rust item | Location | Lean | Relation |"
  echo "|---|---|---|---|"
} > "$out"
while IFS=$'\t' read -r file sym lean rel; do
  [[ -z "$file" || "$file" == \#* ]] && continue
  line="$(git -C "$rust" show "$commit:$file" 2>/dev/null | grep -n -F -m1 -- "$sym" | cut -d: -f1)"
  if [[ -z "$line" ]]; then
    echo "MISSING in Rust: $file: $sym" >&2; fail=1; rloc="\`$file\` (missing)"
  else
    rloc="[$file:$line](rust/$file#L$line)"
  fi
  IFS=$'\t' read -r _ mod lline < <(awk -F'\t' -v n="$lean" '$1 == n { print; exit }' "$tmp/lean.tsv")
  if [[ -z "${mod:-}" || "$mod" == MISSING ]]; then
    echo "MISSING in Lean: $lean" >&2; fail=1; lloc="\`$lean\` (missing)"
  else
    lloc="[\`$lean\`](${mod//.//}.lean#L$lline)"
  fi
  printf '| `%s` | %s | %s | %s |\n' "$sym" "$rloc" "$lloc" "$rel" >> "$out"
done < "$here/scripts/trace.tsv"

files="$(grep -v '^#' "$here/scripts/trace.tsv" | cut -f1 | sort -u)"
{
  echo
  echo "## Drift between the pin and \`$ref\`"
  echo
  if ! git -C "$rust" rev-parse -q --verify "$ref^{commit}" > /dev/null; then
    echo "\`$ref\` is not known in \`rust/\`; drift was not checked."
  else
    changed="$(git -C "$rust" diff --name-only "$commit" "$ref" -- $files)"
    if [[ -z "$changed" ]]; then echo "None of the mapped Rust files differ (\`$ref\` is \`$(git -C "$rust" rev-parse --short "$ref")\`)."
    else echo "Changed (re-check the proofs that map to these files):"; echo; echo "$changed" | sed 's/^/- `/; s/$/`/'; fi
  fi
} >> "$out"
rm -rf "$tmp"
echo "wrote $out"
exit $fail
